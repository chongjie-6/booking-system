CREATE UNIQUE INDEX ON bulk_movies (n);

-- Every bulk screen, every day for two weeks, at 10:00, 13:30, 17:00 and 20:30, each showing a random film.
-- About one in seven is 3D, IMAX or 4D.
INSERT INTO events (movie_id, room_id, format_id, starts_at)
SELECT bm.movie_id, x.room_id, f.format_id, x.starts_at
FROM (
    SELECT r.room_id, 1 + floor(random() * 2000)::int AS mn,
        CASE WHEN random() < 0.86 THEN 'Standard' ELSE (ARRAY['3D', 'IMAX', '4D'])[1 + floor(random() * 3)::int] END AS format,
        ((now() AT TIME ZONE 'Australia/Sydney')::date + d + t) AT TIME ZONE 'Australia/Sydney' AS starts_at
    FROM rooms r
    JOIN cinemas c USING (cinema_id),
    generate_series(0, 13) AS d,
    unnest(ARRAY['10:00', '13:30', '17:00', '20:30']::time[]) AS t
    WHERE c.name NOT IN ('Melbourne Central', 'Mildura')
) AS x
JOIN bulk_movies bm ON bm.n = x.mn
JOIN event_formats f ON f.name = x.format;

-- Bookings of seat pairs (1-2, 3-4, ...) by random bulk users. Each showing gets its own fill rate, 0-40%, so some are
-- nearly empty and some busy. booking_id is made up front so the seats can find their booking.
WITH pair AS MATERIALIZED (
    SELECT uuidv7() AS booking_id, p.event_id, p.room_id, p.row_label, p.pair, bu.user_id, p.starts_at
    FROM (
        SELECT e.event_id, e.room_id, e.starts_at, rl AS row_label, pr AS pair, 1 + floor(random() * 5000)::int AS un,
            e.fill
        FROM (
            SELECT ev.*, random() * 0.4 AS fill
            FROM events ev
            JOIN rooms r USING (room_id)
            JOIN cinemas c USING (cinema_id)
            WHERE c.name NOT IN ('Melbourne Central', 'Mildura')
        ) AS e,
        unnest(string_to_array('A,B,C,D,E,F,G,H', ',')) AS rl,
        generate_series(1, 7) AS pr
    ) AS p
    JOIN bulk_users bu ON bu.n = p.un
    WHERE random() < p.fill
), b AS (
    INSERT INTO bookings (booking_id, event_id, user_id, created_at)
    SELECT booking_id, event_id, user_id, least(now(), starts_at) - make_interval(mins => floor(random() * 20160)::int)
    FROM pair
)
INSERT INTO booking_seats (booking_id, event_id, room_id, seat_id, price_cents)
SELECT pair.booking_id, pair.event_id, pair.room_id, s.seat_id, f.base_price_cents + sts.surcharge_cents + c.surcharge_cents
FROM pair
JOIN events e USING (event_id)
JOIN event_formats f USING (format_id)
JOIN rooms r ON r.room_id = pair.room_id
JOIN cinemas c ON c.cinema_id = r.cinema_id
JOIN seats s ON s.room_id = pair.room_id AND s.row_label = pair.row_label AND s.seat_number IN (pair.pair * 2 - 1, pair.pair * 2)
JOIN seat_type_surcharges sts ON sts.seat_type = s.seat_type;

